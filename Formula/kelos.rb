  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.30.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "2d7046acd12d15de7f42d68a88bd8992a77b0bd4f63ab7b9973bc83d89dc9d2d"
    end
    on_arm do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-arm64"
      sha256 "5887a419d98a3b517cd8571c8efefd852cfbb9e427cc24d216f495fc19f78280"
