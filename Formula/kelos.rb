  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.48.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "ef237f5e171dbac8e314b95ee8e4fd22910c91ad810b7e91c1b6658cc33dbd4f"
    end
    on_arm do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-arm64"
      sha256 "f5d8fc68b387ce46fb5067b4df01cf7ac7251b893df2c0001ce0ac3f94b86c55"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-linux-amd64"
      sha256 "d1cbb2ad31b744a767946b51ab522cbf80996935b0ddc062c3cbf73174215e0e"
