  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.55.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "0b58b9547fee4b46a37ba1d7d7f672ae2f46a18b4fd588773a3c0d0697fcfdde"
