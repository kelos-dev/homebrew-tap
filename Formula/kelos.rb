  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.58.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "a19d9fca94883a0dca9d2065a3a1ec9684ac683a99be6ff9bdb73c35eaeb82b6"
