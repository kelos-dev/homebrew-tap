  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.52.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "2c8fe1356cbf1169632968c0e9f1039acd756b19bd0bba7a1fb2f09312d6d39e"
