  homepage "https://github.com/kelos-dev/kelos"
  license "Apache-2.0"

  version "0.60.0"

  on_macos do
    on_intel do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-amd64"
      sha256 "61a753d4e3414a6983143215b7b564a8dbccf51f1a565e107d0edda291774ec9"
    end
    on_arm do
      url "https://github.com/kelos-dev/kelos/releases/download/v#{version}/kelos-darwin-arm64"
      sha256 "4417741668b8f842cf7941009377bd39d48d20b2fbeb1d226b756dbf88dafdc6"
    end
  end

  on_linux do
